"""Write docs/API.md from the service layer's docstrings and the server's route list.

    python scripts/make_api_docs.py

A test checks that the committed file matches, so the reference cannot drift from the code.
"""

from __future__ import annotations

import inspect
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from taxnetlab.api import Api  # noqa: E402
from taxnetlab.server import ROUTES  # noqa: E402

OUT = ROOT / "docs" / "API.md"


def build() -> str:
    lines = ["# API reference", "",
             "Generated by `scripts/make_api_docs.py`; do not edit by hand.", "",
             "## HTTP interface", "",
             "The interface server listens on 127.0.0.1 only. POST requests need the header `X-TaxNetLab-Token` "
             "(the session token embedded in the page) and `Content-Type: application/json`. Errors are JSON "
             "`{\"error\": {\"code\", \"message\"}}` with status 400, 403, 404, 413, 415, 421 or 422.", "",
             "| Method | Path | Purpose |", "|---|---|---|"]
    lines += [f"| {m} | `{p}` | {d} |".replace("|`", "|`") for m, p, d in ((m, p.replace("|", "\\|"), d) for m, p, d in ROUTES)]
    lines += ["", "## Python service layer (`taxnetlab.api.Api`)", "",
              "The interface, the command line and notebooks use the same class: `Api(Workspace(path))`.", ""]
    for name, fn in inspect.getmembers(Api, predicate=inspect.isfunction):
        if name.startswith("_"):
            continue
        sig = str(inspect.signature(fn)).replace("(self, ", "(").replace("(self)", "()")
        doc = inspect.getdoc(fn) or ""
        lines += [f"### `{name}{sig}`", ""] + ([doc, ""] if doc else [])
    return "\n".join(lines).rstrip() + "\n"


if __name__ == "__main__":
    OUT.write_text(build(), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
