"""Research-run reports (plan Phase 8): a self-contained HTML page for one stored run.

The report states what was run, on what data, with which parameters and assumptions, what came out (a
preview of every output table with its hash), the warnings, the engine's status and boundary, how to cite
the software and how to replay the run. It contains no script and no external resource, so it can be archived
with a paper. Numbers are shown exactly as stored.
"""

from __future__ import annotations

import html
import json
from typing import Any

from taxnetlab import __version__

PREVIEW_ROWS = 40

CSS = """
body{font-family:Georgia,'Times New Roman',serif;max-width:980px;margin:32px auto;padding:0 20px;color:#111;line-height:1.5}
h1{font-size:24px;margin-bottom:4px}h2{font-size:18px;margin-top:28px;border-bottom:1px solid #ccc;padding-bottom:4px}
table{border-collapse:collapse;font-size:12.5px;font-family:Consolas,Menlo,monospace;margin:8px 0;display:block;overflow-x:auto}
th,td{border:1px solid #ccc;padding:3px 6px;text-align:left;vertical-align:top}th{background:#f3f3f3}
.flag{border:2px solid #c2410c;color:#7c2d12;padding:8px 12px;margin:12px 0;background:#fff7ed}
.muted{color:#555;font-size:13px}code{font-family:Consolas,Menlo,monospace;font-size:12.5px}
"""


def _e(x: Any) -> str:
    return html.escape("" if x is None else str(x))


def _table(columns: list[str], rows: list[dict[str, Any]]) -> str:
    head = "".join(f"<th>{_e(c)}</th>" for c in columns)
    body = "".join("<tr>" + "".join(f"<td>{_e(r.get(c))}</td>" for c in columns) + "</tr>" for r in rows)
    return f"<table><thead><tr>{head}</tr></thead><tbody>{body}</tbody></table>"


def run_report_html(record: dict[str, Any], outputs: dict[str, dict[str, Any]], citation: str | None = None) -> str:
    eng, ds = record["engine"], record["dataset"]
    flags = []
    if ds["data_status"] == "synthetic":
        flags.append("Synthetic data: every jurisdiction, company, value and rate is fictional.")
    if eng["status"] not in ("verified", "replicated", "replicated_with_discrepancies", "robust", "empirically_tested"):
        flags.append(f"Engine status '{eng['status']}': the method's specification has not yet been verified against its "
                     "source, so results are not citable as a reproduction of the published method.")
    if eng["track"] == "demonstration":
        flags.append("Demonstration engine: not a research method.")
    if record.get("_integrity", "ok") != "ok":
        flags.append("The run record has been modified since it was written; its hash does not match.")
    parts = [f"<!doctype html><html lang='en-GB'><head><meta charset='utf-8'><title>Run {_e(record['run_id'])}</title>"
             f"<style>{CSS}</style></head><body>",
             f"<h1>Research run {_e(record['run_id'])}</h1>",
             f"<p class='muted'>International Tax Network Lab {_e(record['environment'].get('taxnetlab_version', ''))}; "
             f"report generated by version {_e(__version__)}. Not tax or legal advice; network position is not evidence "
             "of avoidance or illegality.</p>"]
    parts += [f"<div class='flag'>{_e(f)}</div>" for f in flags]
    parts.append("<h2>Question</h2><p>" + (_e(record.get("research_question")) or "<span class='muted'>(none recorded)</span>")
                 + "</p>")
    parts.append("<h2>Method</h2>" + _table(["field", "value"], [
        {"field": "engine", "value": f"{eng['display_name']} ({eng['engine_id']})"},
        {"field": "track, variant, version", "value": f"{eng['track']}, {eng['variant']}, {eng['version']}"},
        {"field": "status", "value": eng["status"]}, {"field": "specification", "value": eng["spec_ref"]},
        {"field": "boundary", "value": eng["boundary"]}, {"field": "outcome", "value": record["outcome"]},
        {"field": "started (UTC)", "value": record["started_utc"]}, {"field": "finished (UTC)", "value": record["finished_utc"]}]))
    parts.append("<h2>Data</h2>" + _table(["field", "value"], [
        {"field": "dataset", "value": f"{ds['name']} ({ds['dataset_id']})"}, {"field": "content hash", "value": ds["content_hash"]},
        {"field": "data status", "value": ds["data_status"]}])
                 + _table(["source_id", "title", "licence_class"], ds.get("sources", [])))
    parts.append("<h2>Parameters</h2>" + _table(["parameter", "value"], [
        {"parameter": k, "value": json.dumps(v, ensure_ascii=False) if isinstance(v, (list, dict)) else v}
        for k, v in sorted(record["parameters"].items())]))
    if record.get("assumptions"):
        parts.append("<h2>Assumptions</h2><ul>" + "".join(f"<li>{_e(a)}</li>" for a in record["assumptions"]) + "</ul>")
    if record.get("warnings"):
        parts.append("<h2>Warnings</h2><ul>" + "".join(f"<li>{_e(w)}</li>" for w in record["warnings"]) + "</ul>")
    if record.get("trace"):
        parts.append("<h2>Calculation trace</h2>" + _table(["step", "description", "detail", "result"], record["trace"]))
    parts.append("<h2>Outputs</h2>")
    for name, info in record["outputs"].items():
        out = outputs.get(name, {"columns": [], "rows": []})
        rows = out["rows"]
        parts.append(f"<h3>{_e(name)}</h3><p class='muted'>{len(rows)} rows; SHA-256 <code>{_e(info['sha256'])}</code>"
                     + (f"; first {PREVIEW_ROWS} shown" if len(rows) > PREVIEW_ROWS else "") + "</p>")
        parts.append(_table(list(out["columns"]), rows[:PREVIEW_ROWS]))
    env = record.get("environment", {})
    parts.append("<h2>Reproduction</h2><p>Replay this run with <code>taxnetlab replay "
                 f"{_e(record['run_id'])}</code> in a workspace holding dataset <code>{_e(ds['dataset_id'])}</code>; the "
                 "replay re-executes the engine and compares every output hash.</p>"
                 + _table(["field", "value"], [{"field": k, "value": v} for k, v in sorted(env.items())
                                               if not isinstance(v, (dict, list))])
                 + f"<p class='muted'>Record hash <code>{_e(record.get('record_sha256'))}</code>.</p>")
    if citation:
        parts.append(f"<h2>How to cite the software</h2><p>{_e(citation)}</p>")
    parts.append("</body></html>")
    return "\n".join(parts)
